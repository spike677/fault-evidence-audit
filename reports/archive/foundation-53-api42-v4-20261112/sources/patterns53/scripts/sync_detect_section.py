#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
把 L2 判据层与 L3 判据失效警示写进深度档 SKILL.md（sync_detect_section.py，v6.18.1）

问题
----
v6.17/v6.18 把库补成三层（L1 机理 / L2 判据 / L3 失效模式），但 L2/L3 只落在
`fault_patterns_detect.json` 与索引里，52 份 SKILL.md 中**一份都没引用** detect 字段。
Agent 的实际执行路径是 `workflows → skills`，不是 README——于是新增的两层
在实际检视中读不到，「怎么测」和「这个 oracle 会怎么骗你」都没有进入动作序列。

做法
----
对 `depth=深度` 的技能，在文末追加一节（带 BEGIN/END 标记，可重复运行覆盖）：

  - L2：本模式 axes / oracle / signal / lines / min_cases / constructor / judge / kill
  - L3：本模式用到的每个 oracle 类别，各列其失效条目（至少含假 FAIL 与假 PASS 两侧）
  - 判读纪律：FAIL 前查假 FAIL、PASS 前查假 PASS

**只做搬运，不做编写**：本节内容逐字来自索引，改判据请改真源后跑 `gen_detect.py`
再跑本脚本；守门 **C42** 校验本节与索引逐字一致，防「改了索引忘了同步技能」。

用法
----
python3 scripts/sync_detect_section.py            # 写入/更新全部深度档技能
python3 scripts/sync_detect_section.py --check    # 只校验（供 CI），不一致返回 3
python3 scripts/sync_detect_section.py --dry-run  # 打印将写入的目标，不落盘

退出码
------
0 = 一致（或已写入）｜ 3 = --check 模式下有不一致 ｜ 1 = 环境/参数错误
"""

import argparse
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
# 标记必须与标题**同行**，不能单独占一行。原因：`gen_cases.py` 的 `section()` 从
# 「`## N. 已知缺陷案例库`」扫到**下一个 `## ` 行**才截断，案例块又在 `### 案例 N｜` 处切分。
# 若 BEGIN 单独一行置于 `## N.` 之上，这一行会落在案例库区间内、并被并入最后一个案例块，
# 其中的 `scripts/*.py` 路径会被 `case_locators()` 当作真实锚抽进 cases.json
# （实测后果：FP-G02-C12 等 20 条案例各多出一个 `scripts/sync_detect_section.py` 锚）。
BEGIN = "<!-- BEGIN DETECT-SECTION (generated by scripts/sync_detect_section.py; do not edit) -->"
END = "<!-- END DETECT-SECTION -->"

# 失效方向归类：用于择优展示，确保「假 FAIL」和「假 PASS」两侧都出现在技能里
FALSE_FAIL_HINTS = ("假 FAIL", "假红", "假阳", "假缺陷")
FALSE_PASS_HINTS = ("假 PASS", "假通过", "假绿", "漏检", "静默漏判", "静默假 PASS")

COVER_RE = re.compile(
    r"^\|\s*\[(FP-[A-G]\d{2})\]\(([^)]+)\)\s*\|[^|]+\|\s*`([^`]+)`\s*\|")

AXIS_ZH = {
    "content": "内容取值", "shape": "shape 维度", "dtype": "dtype 分支",
    "sequence": "执行序列", "input-validity": "入参合法性", "contract": "契约一致性",
    "golden": "golden 口径", "boundary": "边界值", "perf": "性能",
    "memory": "内存", "attr": "属性", "concurrency": "并发/同步",
    "doc": "文档声明", "bitwise": "逐位一致",
}


def read_text(path):
    with open(path, encoding="utf-8-sig") as f:
        return f.read()


def load_index(root):
    return json.loads(read_text(os.path.join(root, "fault_patterns_index.json")))


def skill_map(root):
    """skills/README.md 覆盖表 → {fp_id: SKILL.md 绝对路径}。"""
    out = {}
    readme = os.path.join(root, "skills", "README.md")
    for line in read_text(readme).splitlines():
        m = COVER_RE.match(line)
        if not m:
            continue
        fp_id, rel = m.group(1), m.group(2)
        out[fp_id] = os.path.normpath(os.path.join(root, "skills", rel))
    return out


def _side(fail_text):
    if any(h in fail_text for h in FALSE_FAIL_HINTS):
        return "fail"
    if any(h in fail_text for h in FALSE_PASS_HINTS):
        return "pass"
    return "other"


def pick_entries(entries, cap_per_side=2):
    """两个失效方向各取前若干条，保证「假 FAIL」与「假 PASS」两侧都能被读到。

    返回 (chosen, sides_present)；sides_present 用于在渲染时标注「该类只记录了单向失效」——
    D29 只要求全库同时覆盖两类，不要求每个 oracle 类别都覆盖，所以单向类是合法数据，
    但必须显式告知读者「别以为没有反向风险」。
    """
    buckets = {"fail": [], "pass": [], "other": []}
    for idx, item in enumerate(entries):
        buckets[_side(str(item.get("fail") or ""))].append(idx)
    chosen = buckets["fail"][:cap_per_side] + buckets["pass"][:cap_per_side]
    if not chosen:
        chosen = buckets["other"][:cap_per_side]
    present = {k for k, v in buckets.items() if v}
    return [entries[i] for i in sorted(chosen)], present


def strip_section(text):
    """剔除既有本节（含标题整行），返回剩余文本；无本节时原样返回。

    按行剔除而非按 `index(BEGIN)` 切：BEGIN 与 `## N.` 标题同行，从标记处切会留下
    行首的 `## N.` 残行，下一轮 `next_section_no` 会把它当成别的章节，编号就一路涨。
    """
    if BEGIN not in text or END not in text:
        return text
    lines = text.split("\n")
    out, skipping = [], False
    for line in lines:
        if not skipping and BEGIN in line:
            skipping = True
        if not skipping:
            out.append(line)
        if skipping and END in line:
            skipping = False
    return "\n".join(out)


def next_section_no(text):
    """本文件已有（不含本节自身）的最大 `## N.` 编号 + 1。

    不能写死 12：库内已有 §11/§12/§13 三种终点（如 fpb11/fpb12/fpb14 到 §13），
    写死会与既有编号撞车。必须先剔除既有本节再取最大值，否则重跑一次编号就 +1 一次。
    """
    nums = [int(m) for m in re.findall(r"^##\s+(\d+)\.", strip_section(text), re.M)]
    return (max(nums) + 1) if nums else 1


def render_section(entry, oracle_failures, sec_no=12):
    """渲染 SKILL.md 内的**指针段**（完整判据见 references/detect-l2-l3.md）。

    为什么不把完整判据内联：`score_skills.py` 的 `fit` 按技能体积打分（18~30KB 满分，
    >36KB 直接掉到 4 分），而 6 份深度档技能已在 35KB 左右——内联 1.7KB 会让它们集体
    跨越阈值、fit 从 7 掉到 4，等于用「技能变臃肿」换「判据可读」。改为渐进披露：
    完整内容落 `references/`，SKILL.md 只留出行动力的指针 + 最关键的 L3 一句。
    这也与 `skills/README.md` 第 25 条（允许 `references/` 附属文件）一致。
    """
    detect = entry.get("detect") or {}
    axes = detect.get("axes") or []
    oracles = detect.get("oracle") or []
    min_cases = detect.get("min_cases", "—")

    def fmt_axes(xs):
        return "/".join(AXIS_ZH.get(x, x) for x in xs) or "—"

    out = [
        "## %d. 判据层（L2/L3）：出用例与判读前必读 %s" % (sec_no, BEGIN),
        "",
        "> 生成物，勿手改（C42 校验）。完整判据见 "
        "[references/%s](references/%s)。" % (REF_NAME, REF_NAME),
        "",
        "- **L2**：轴 %s｜观测 %s｜至少 %s 例"
        % (fmt_axes(axes), "/".join(oracles) or "—", min_cases),
    ]
    for oracle in oracles:
        items = oracle_failures.get(oracle) or []
        if not items:
            out.append("- **L3 `%s`**：无失效清单（D23 应拦截）" % oracle)
            continue
        shown, _present = pick_entries(items, cap_per_side=1)
        tips = "；".join("%s(%s)%s" % (i.get("id"), i.get("fail"),
                                      str(i.get("rule") or "").strip()) for i in shown)
        out.append("- **L3 `%s`**：%s" % (oracle, tips))
    out += [
        "",
        "> 判 FAIL 先排「假 FAIL」、判 PASS 先排「假 PASS/假绿」。**不查 L3 就出结论 = 报告作废。** %s" % END,
    ]
    return "\n".join(out)


def render_reference(entry, oracle_failures):
    """渲染 references/detect-l2-l3.md 全文（L2 全字段 + L3 每类失效条目）。"""
    fp_id = entry.get("id")
    detect = entry.get("detect") or {}
    axes = detect.get("axes") or []
    oracles = detect.get("oracle") or []
    lines = detect.get("lines") or []

    def fmt_axes(xs):
        return " / ".join("%s（%s）" % (x, AXIS_ZH.get(x, x)) for x in xs) or "—"

    out = [
        "# %s 判据层：L2 怎么测 / L3 会怎么骗你" % fp_id,
        "",
        "> 由 `scripts/sync_detect_section.py` 从 `fault_patterns_index.json` 生成，**勿手改**；"
        "守门 **C42** 校验与索引逐字一致。",
        "> 改判据：真源 `fault_patterns_detect.json` → `python3 scripts/gen_detect.py` → "
        "`python3 scripts/sync_detect_section.py`。",
        "",
        "## L2：怎么测才测得出",
        "",
        "| 项 | 内容 |",
        "|---|---|",
        "| 遍历轴 `axes` | %s |" % fmt_axes(axes),
        "| 观测手段 `oracle` | %s |" % (" / ".join("`%s`" % o for o in oracles) or "—"),
        "| 信号类型 `signal` | %s |" % (("`%s`" % detect.get("signal")) if detect.get("signal") else "—"),
        "| 执行线 `lines` | %s |" % (" / ".join("`%s`" % l for l in lines) or "—"),
        "| 最少用例数 `min_cases` | %s |" % detect.get("min_cases", "—"),
        "| 造数据 `constructor` | %s |" % (detect.get("constructor") or "—").replace("|", "\\|"),
        "| 判据 `judge` | %s |" % (detect.get("judge") or "—").replace("|", "\\|"),
        "| 判别力 `kill` | %s |" % (detect.get("kill") or "—").replace("|", "\\|"),
        "",
        "> 只读 L1 机理卡会产出「不得复现该现象」的空壳用例；按上表 `axes` 铺开、"
        "按 `min_cases` 定量、按 `judge` 判成立才算可上板。",
        "",
        "## L3：这些 oracle 本身会怎么骗你（判读前必查）",
        "",
    ]

    total = 0
    for oracle in oracles:
        items = oracle_failures.get(oracle) or []
        total += len(items)
        if not items:
            out.append("- `%s`：**无失效清单**（守门 D23 应拦截，请报缺陷）" % oracle)
            out.append("")
            continue
        shown, present = pick_entries(items)
        out.append("### `%s`（共 %d 条）" % (oracle, len(items)))
        out.append("")
        for item in shown:
            out.append("- `%s`（%s）%s" % (item.get("id"), item.get("fail"),
                                          str(item.get("rule") or "").strip()))
        missing = []
        if "fail" not in present:
            missing.append("「假 FAIL」")
        if "pass" not in present:
            missing.append("「假 PASS / 假绿」")
        if missing:
            out.append("- **注意**：该类目前未登记%s侧——不代表该方向不存在，"
                       "实测踩到后请回补 L3（D29 只要求全库两类都覆盖，不强制每类双向）。"
                       % "、".join(missing))
        out.append("")

    out += [
        "---",
        "",
        "判 FAIL 前先排除该 oracle 的「假 FAIL」类失效；判 PASS 前先排除「假 PASS / 假绿 / 漏检」类失效。"
        "**不查 L3 就报缺陷或报通过，报告作废。**",
        "",
        "全文不在本库复制：拿 K 号去 `aclnn-bug-hunt` 的 `references/pitfalls/` grep。"
        "本节共引用 %d 条 L3 判据。 %s" % (total, END),
    ]
    return "\n".join(out)


def apply_section(text, section):
    """用新生成的 section 替换既有本节；无本节则追加到文末。

    **必须落在文末**：本库 `gen_cases.py` 的 `section()` 从「`## N. 已知缺陷案例库`」扫到
    下一个 `## ` 行才截断，案例块再按 `### 案例 N｜` 切分。若本节被插在案例库中间，
    其内容会被并入最后一个案例块，`scripts/*.py` 会被抽成 `criteria.locators` 真实锚
    （实测：20 条案例各多出一个 `scripts/sync_detect_section.py` 锚）。
    """
    if BEGIN in text and END in text:
        return strip_section(text).rstrip("\n") + "\n\n" + section + "\n"
    return text.rstrip("\n") + "\n\n" + section + "\n"


REF_NAME = "detect-l2-l3.md"


def targets(root):
    """返回 [(fp_id, skill_path, section, ref_path, ref_text)]，只含 depth=深度 的技能。"""
    idx = load_index(root)
    smap = skill_map(root)
    oracle_failures = ((idx.get("detect_layer") or {}).get("oracle_failures") or {}).get("by_oracle") or {}
    out = []
    for entry in idx.get("patterns", []):
        if entry.get("depth") != "深度":
            continue
        fp_id = entry.get("id")
        path = smap.get(fp_id)
        if not path:
            continue
        text = read_text(path) if os.path.isfile(path) else ""
        sec_no = next_section_no(text)
        ref = os.path.join(os.path.dirname(path), "references", REF_NAME)
        out.append((fp_id, path,
                    render_section(entry, oracle_failures, sec_no),
                    ref, render_reference(entry, oracle_failures)))
    return out


def extract_section(text):
    """提取既有本节原文（**含 `## N.` 标题行**，与 render_section 的输出同形）；无则 None。

    不能用 `text[index(BEGIN):...]` 切片：BEGIN 在标题行尾，从标记切会丢掉标题前缀，
    与生成物永远不相等 → `--check` 恒报不一致（已实测）。
    """
    if BEGIN not in text or END not in text:
        return None
    lines = text.split("\n")
    out, started = [], False
    for line in lines:
        if not started and BEGIN in line:
            started = True
        if started:
            out.append(line)
        if started and END in line:
            return "\n".join(out)
    return None


def run(root, check=False, dry=False):
    items = targets(root)
    if not items:
        print("[FAIL] 未找到任何深度档技能（检查 index depth 与 skills/README 覆盖表）")
        return 1
    stale = []
    for fp_id, path, section, ref_path, ref_text in items:
        if not os.path.isfile(path):
            print("[FAIL] %s 对应 SKILL.md 不存在：%s" % (fp_id, path))
            return 1
        text = read_text(path)
        ref_now = read_text(ref_path) if os.path.isfile(ref_path) else None
        if extract_section(text) == section and ref_now == ref_text:
            continue
        stale.append(fp_id)
        if check or dry:
            continue
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write(apply_section(text, section))
        os.makedirs(os.path.dirname(ref_path), exist_ok=True)
        with open(ref_path, "w", encoding="utf-8", newline="\n") as f:
            f.write(ref_text)
    if check:
        if stale:
            print("[FAIL] 以下深度档技能的判据指针/参考文件与索引不一致"
                  "（跑 sync_detect_section.py）：%s" % "、".join(stale))
            return 3
        print("[PASS] 判据指针 + references 一致：%d 份深度档技能" % len(items))
        return 0
    if dry:
        print("[DRY] 将更新 %d 份（不一致 %d 份）：%s"
              % (len(items), len(stale), "、".join(stale) or "无"))
        return 0
    print("[OK] 已同步判据指针 + references：%d 份深度档技能，本次更新 %s"
          % (len(items), "、".join(stale) or "无（已是最新）"))
    return 0


def main(argv=None):
    ap = argparse.ArgumentParser(description="把 L2 判据层与 L3 失效警示写进深度档 SKILL.md")
    ap.add_argument("--root", default=ROOT)
    ap.add_argument("--check", action="store_true", help="只校验，不一致返回 3")
    ap.add_argument("--dry-run", action="store_true", help="不落盘")
    args = ap.parse_args(argv)
    return run(os.path.abspath(args.root), check=args.check, dry=args.dry_run)


if __name__ == "__main__":
    sys.exit(main())
